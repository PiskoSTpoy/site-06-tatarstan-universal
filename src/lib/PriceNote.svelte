<script lang="ts">
	/*
	 * Разбор ориентировочной цены на карточке техники.
	 *
	 * Зачем компонент, а не абзац на каждой странице: в таблице характеристик стоит одно число
	 * («от 40 000 ₽ за 8 часов»), и без пояснения оно читается как прайс-лист компании. Это не
	 * прайс-лист: число взято из открытых прайсов сторонних операторов, источник подписан ниже
	 * на самой странице. Дальше — ровно то, что про эту цифру ИЗВЕСТНО, и явно названное то,
	 * что про неё НЕ известно.
	 *
	 * Чего здесь сознательно НЕТ: минимального заказа, стоимости подачи в рублях, ставки НДС и
	 * состава работ «под ключ». Это коммерческие условия конкретного юридического лица —
	 * данные заказчика того же класса, что ИНН и ОГРН. Подставить сюда правдоподобные числа
	 * означало бы выдумать условия договора, по которым потом будут считать бюджет.
	 */
	let {
		unit = 'смена 8 часов',
		checkedIso,
		checkedText,
		sourceNote,
	}: {
		/** единица тарификации, в которой указана цифра в таблице характеристик */
		unit?: string;
		/** дата проверки источника цены, ISO — для машиночитаемого <time> */
		checkedIso: string;
		/** та же дата в том виде, в каком её читает человек */
		checkedText: string;
		/** чем именно является источник цифры на этой конкретной странице */
		sourceNote: string;
	} = $props();
</script>

<section class="pn">
