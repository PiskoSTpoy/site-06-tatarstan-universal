			<dd>{unit}. Цифра в таблице выше указана за смену, не за час и не за объект целиком.</dd>
		</div>
		<div class="pn__row">
			<dt>Откуда цифра</dt>
			<dd>{sourceNote} Источники подписаны ниже на этой же странице.</dd>
		</div>
		<div class="pn__row">
			<dt>Что входит в смену</dt>
			<dd>
				Часы работы крана по сменному рапорту, подписанному на объекте: простой фиксируется там же
				отдельной строкой с указанием причины, а на режимном объекте в рапорт попадает и время,
				потраченное на проходной. Как устроен рапорт и договор аренды с экипажем — на странице
				<a href="/documents/">«Документы и согласования»</a>.
			</dd>
		</div>
		<div class="pn__row">
			<dt>Что не входит</dt>
			<dd>
				Подача и перегон техники до объекта: в исходных прайсах указана ставка за работу машины на
				площадке, стоимость доставки в них отдельной строкой не приведена, и мы её не додумываем.
			</dd>
		</div>
		<div class="pn__row">
			<dt>НДС</dt>
			<dd>
				В исходных прайсах НДС не выделен, поэтому считать эту цифру ставкой с НДС или без НДС
				нельзя — налоговый режим определяется договором с конкретным исполнителем.
			</dd>
		</div>
	</dl>
	<p class="pn__disc">
		Цифра приведена как рыночный ориентир и <strong>не является публичной офертой</strong> (ст. 437
		ГК РФ). Источники цены проверены
		<time datetime={checkedIso}>{checkedText}</time>.
	</p>
</section>

