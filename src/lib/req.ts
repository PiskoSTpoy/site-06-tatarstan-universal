/**
 * Требование раздела допуска — четыре поля, из которых состоит любая строка чек-листа
 * на этом сайте: ЧТО нужно, НА КАКОМ основании, КТО оформляет, ЧТО СО СРОКОМ.
 *
 * Тип вынесен в отдельный модуль, а не объявлен внутри Reqs.svelte: страницы импортируют
 * его напрямую вместе с компонентом, и держать типы в компоненте значило бы тащить
 * инстанс-скрипт ради одной аннотации.
 */
export type ReqItem = {
	/** Само требование одной строкой — то, что должно быть оформлено или обеспечено. */
	what: string;
	/** Норма или документ, из которого требование следует. Без источника пункт не публикуем. */
	basis: string;
	/** Сторона, которая физически оформляет: предприятие, подрядчик, надзорный орган. */
	who: string;
	/** Срок действия, периодичность или момент оформления. */
	term: string;
	/** Необязательная сноска: оговорка, честное «данных нет», практическое следствие. */
	note?: string;
};
